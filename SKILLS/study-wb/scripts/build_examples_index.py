#!/usr/bin/env python3
"""build_examples_index.py - regenerate examples/index.data.js, the data behind the examples gallery (examples/index.html).

    python build_examples_index.py

Reads every examples/<folder>/<folder>.yaml, expands it the way the build does, and records what the gallery shows:
title, heading, the one-line description from the file's header comment, subject, groups, problems, label counts,
widgets used, workbench tools, and the page and content paths. The gallery page itself is static; only this data file
is generated, so the cards never drift from the content. Writes only when the data changed.
"""
import json
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from study_wb_lib import expand, load_content, write_if_changed  # noqa: E402

EX = Path(__file__).resolve().parent.parent / "examples"
WIDGETS = ("classify", "answers", "choice", "table", "fset")
SUBJECT = [("accounting", "Accounting"), ("circuits", "Science"), ("mechanics", "Science"), ("chemistry", "Science"), ("minimal", "Starter")]


def describe(text: str) -> str:
    m = re.search(r"#\s*study-wb example:\s*(.+?)(?:\n#\s*\n|\n[^#])", text, re.S)
    if not m:
        return ""
    return re.sub(r"\s*\n#\s*", " ", m.group(1)).strip()


def main() -> int:
    cards = []
    for folder in sorted(p for p in EX.iterdir() if p.is_dir()):
        src = folder / f"{folder.name}.yaml"
        if not src.exists():
            continue
        raw = src.read_text(encoding="utf-8")
        content = load_content(src)
        data = expand(content)
        probs = [p for g in data.get("groups", []) for p in g.get("problems", [])]
        labels = {k: sum(1 for p in probs if p.get("label") == k) for k in ("graded", "calculated", "generated")}
        widgets = sorted({w for w in WIDGETS if re.search(rf"^\s*-\s*{w}:", raw, re.M)} | ({"fset"} if 'class="fset"' in raw else set()))
        wb = content.get("workbench") or {}
        tools = wb.get("toolsOffered") or wb.get("tools") or ["calculator", "notepad", "stickies"]
        name = (content.get("build") or {}).get("name") or folder.name
        cards.append({
            "id": folder.name,
            "subject": next((s for k, s in SUBJECT if folder.name.startswith(k)), "Other"),
            "title": (content.get("page") or {}).get("title", folder.name).replace(" (example)", ""),
            "heading": (content.get("page") or {}).get("heading", ""),
            "description": describe(raw),
            "groups": [g.get("id") for g in data.get("groups", [])],
            "problems": len(probs),
            "labels": labels,
            "widgets": widgets,
            "tools": tools,
            "timer": bool(content.get("timer")),
            "page": f"{folder.name}/{name}.html",
            "content": f"{folder.name}/{src.name}",
            "sources": sorted(str(p.relative_to(folder)).replace("\\", "/") for p in (folder / "sources").glob("*")) if (folder / "sources").exists() else [],
            "built": (folder / f"{name}.html").exists(),
        })
    payload = "/* Generated by scripts/build_examples_index.py - do not edit. */\nwindow.STUDY_WB_EXAMPLES = " + json.dumps(cards, ensure_ascii=False, indent=1) + ";\n"
    changed = write_if_changed(EX / "index.data.js", payload.encode("utf-8"))
    print(f"{len(cards)} examples; index.data.js {'written' if changed else 'unchanged'}")
    missing = [c["id"] for c in cards if not c["built"]]
    if missing:
        print("not built yet (run build_study_aid.py on each): " + ", ".join(missing))
    return 0


if __name__ == "__main__":
    sys.exit(main())
