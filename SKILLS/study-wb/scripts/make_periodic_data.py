#!/usr/bin/env python3
"""make_periodic_data.py - regenerate lib/workbench/periodic/elements.js from PubChem's periodic table.

    python make_periodic_data.py PUBCHEM_CSV [--retrieved YYYY-MM-DD]

PUBCHEM_CSV is the file served by https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/CSV (download it with any
HTTP client; this script does not touch the network). Values are copied, never edited. Group and period are not in
the CSV; they follow from the atomic number by the standard 18-column layout (lanthanoids 57-71 and actinoids
89-103 get no group and are drawn in the two rows below the table). Standard library only.
"""
import argparse
import csv
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parent.parent / "lib" / "workbench" / "periodic" / "elements.js"
PERIOD_START = [(1, 1), (3, 2), (11, 3), (19, 4), (37, 5), (55, 6), (87, 7)]


def period_of(z: int) -> int:
    return max(p for start, p in PERIOD_START if z >= start)


def group_of(z: int):
    p = period_of(z)
    start = dict((pp, s) for s, pp in PERIOD_START)[p]
    i = z - start
    if p == 1:
        return 1 if z == 1 else 18
    if p in (2, 3):
        return i + 1 if i < 2 else i + 11
    if p in (4, 5):
        return i + 1
    if i < 2:
        return i + 1
    if i <= 16:
        return None                      # lanthanoid / actinoid row
    return i - 13


def num(s):
    s = (s or "").strip()
    if not s:
        return None
    try:
        return float(s)
    except ValueError:
        return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("csv", type=Path)
    ap.add_argument("--retrieved", required=True, help="date the CSV was downloaded, YYYY-MM-DD")
    a = ap.parse_args()
    rows = list(csv.DictReader(a.csv.open(encoding="utf-8-sig", newline="")))
    if len(rows) != 118:
        print(f"expected 118 elements, got {len(rows)}", file=sys.stderr)
        return 1
    els = []
    for r in rows:
        z = int(r["AtomicNumber"])
        els.append([z, r["Symbol"], r["Name"], r["AtomicMass"].strip(), num(r["Electronegativity"]), r["StandardState"].strip(),
                    r["GroupBlock"].strip(), group_of(z), period_of(z), r["ElectronConfiguration"].strip()])
    if [e[0] for e in els] != list(range(1, 119)):
        print("atomic numbers are not 1..118 in order", file=sys.stderr)
        return 1
    header = ("/* Generated by scripts/make_periodic_data.py - do not edit by hand.\n"
              f"   Source: PubChem Periodic Table, National Center for Biotechnology Information (NCBI),\n"
              "   https://pubchem.ncbi.nlm.nih.gov/rest/pug/periodictable/CSV, retrieved " + a.retrieved + ".\n"
              "   Atomic masses are PubChem's values, copied as text (unrounded). Group and period are derived from the\n"
              "   atomic number by the standard 18-column layout; lanthanoids and actinoids have no group here.\n"
              "   Row: [Z, symbol, name, atomic mass, electronegativity (Pauling), standard state, block, group, period, configuration] */\n")
    body = "window.STUDY_WB_ELEMENTS = {\n  source: " + json.dumps(f"PubChem Periodic Table (NCBI), retrieved {a.retrieved}") + ",\n  rows: [\n"
    body += ",\n".join("    " + json.dumps(e, ensure_ascii=False) for e in els) + "\n  ]\n};\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(header + body, encoding="utf-8", newline="\n")
    print(f"wrote {OUT} ({len(els)} elements)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
